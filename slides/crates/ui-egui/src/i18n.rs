/// Saved as its code (`ar`, `pt-br`).
impl Serialize for Language {
    fn serialize<S: serde::Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
        s.serialize_str(self.code())
    }
}

/// Read from its code or any language tag; one this build doesn't have is English.
impl<'de> Deserialize<'de> for Language {
    fn deserialize<D: serde::Deserializer<'de>>(d: D) -> Result<Language, D::Error> {
        lenient(d)
    }
}

/// A saved language read leniently: one this build doesn't have (or not a string) is English,
/// so the rest of the saved settings still load.
pub fn lenient<'de, D: serde::Deserializer<'de>>(d: D) -> Result<Language, D::Error> {
    let v = serde_json::Value::deserialize(d)?;
    Ok(v.as_str().and_then(Language::parse).unwrap_or_default())
}

thread_local! {
    static CURRENT: std::cell::Cell<Language> = const { std::cell::Cell::new(Language::En) };
}

/// The interface language this thread draws in.
pub fn current() -> Language {
    CURRENT.with(std::cell::Cell::get)
}

/// `text` in the interface language, for text painted without a widget.
pub fn tr(text: &str) -> &str {
    current().tr(text)
}

/// The interface's words for empty placeholders' prompts, for the slide renderer.
pub fn prompts() -> Option<fn(&str) -> Option<&'static str>> {
    match current() {
        Language::En => None,
        _ => Some(|t| current().lookup(t)),
    }
}

/// Draw `ctx` in `language`: its widgets' words, and the direction.
pub fn install(ctx: &egui::Context, language: Language) {
    let was = current();
    CURRENT.with(|c| c.set(language));
    crate::rtl::set(ctx, language.is_rtl());
    if was != language || ctx.translate("Home").is_none() != (language == Language::En) {
        ctx.set_translator(match language {
            Language::En => None,
            lang => Some(std::sync::Arc::new(move |t: &str| lang.lookup(t).map(str::to_owned))),
        });
    }
}

